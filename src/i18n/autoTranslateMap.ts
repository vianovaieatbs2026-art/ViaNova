/**
 * Translates English text back into Spanish
 */
export function translateTextToSpanish(text: string): string {
  if (!text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Exact match
  if (ENGLISH_TO_SPANISH_MAP[trimmed]) {
    return text.replace(trimmed, ENGLISH_TO_SPANISH_MAP[trimmed]);
  }

  // 2. Case-insensitive lookup
  const lower = trimmed.toLowerCase();
  for (const [enKey, esVal] of Object.entries(ENGLISH_TO_SPANISH_MAP)) {
    if (enKey.toLowerCase() === lower) {
      if (trimmed === trimmed.toUpperCase() && trimmed.length > 3) {
        return text.replace(trimmed, esVal.toUpperCase());
      }
      return text.replace(trimmed, esVal);
    }
  }

  // 3. Dynamic regex patterns
  let working = text;
  working = working.replace(/Results found \((.*?)\)/gi, 'Resultados encontrados ($1)');
  working = working.replace(/Question (\d+) of (\d+)/gi, 'Pregunta $1 de $2');
  working = working.replace(/(\d+) minutes ago/gi, 'Hace $1 minutos');
  working = working.replace(/(\d+) hours ago/gi, 'Hace $1 horas');
  working = working.replace(/Just now/gi, 'Hace un momento');
  working = working.replace(/(\d+) certified hours/gi, '$1 horas certificadas');
  working = working.replace(/(\d+) evaluations/gi, '$1 evaluaciones');
  working = working.replace(/(\d+) questions/gi, '$1 preguntas');
  working = working.replace(/Limit:? (\d+) km\/h/gi, 'Límite: $1 km/h');
  working = working.replace(/Maximum speed:? (\d+) km\/h/gi, 'Velocidad máxima: $1 km/h');
  working = working.replace(/Score:? (\d+)%/gi, 'Puntaje: $1%');
  working = working.replace(/Module (\d+):?/gi, 'Módulo $1:');
  working = working.replace(/Step (\d+):?/gi, 'Paso $1:');

  // 4. Substring / multi-word phrase replacement (longest multi-word English phrases first)
  const enPhrases = Object.keys(ENGLISH_TO_SPANISH_MAP)
    .filter(k => k.includes(' ') && k.length >= 4)
    .sort((a, b) => b.length - a.length);

  for (const enPhrase of enPhrases) {
    if (working.includes(enPhrase)) {
      working = working.split(enPhrase).join(ENGLISH_TO_SPANISH_MAP[enPhrase]);
    }
  }

  // 5. Word-by-word token fallback for individual English words
  const tokens = working.split(/(\s+|[.,;:?!()\[\]{}"'¿¡]+)/);
  let changed = false;
  const translatedTokens = tokens.map((token) => {
    if (!token || /^\s+$/.test(token) || /^[.,;:?!()\[\]{}"'¿¡]+$/.test(token)) {
      return token;
    }
    const tokenLower = token.toLowerCase();
    if (ENGLISH_TO_SPANISH_MAP[tokenLower]) {
      changed = true;
      const mapped = ENGLISH_TO_SPANISH_MAP[tokenLower];
      if (token === token.toUpperCase() && token.length > 1) {
        return mapped.toUpperCase();
      }
      if (token[0] === token[0].toUpperCase()) {
        return mapped.charAt(0).toUpperCase() + mapped.slice(1);
      }
      return mapped;
    }
    return token;
  });

  if (changed) {
    working = translatedTokens.join('');
  }

  return working;
}
