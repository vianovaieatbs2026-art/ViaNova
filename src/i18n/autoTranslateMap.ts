/**
 * Universal Spanish to English Sentence and Phrase Translator
 * 1. Checks exact match in comprehensive dictionary.
 * 2. Checks case-insensitive match.
 * 3. Handles dynamic regex patterns (e.g. counts, dates, speeds).
 * 4. Replaces known multi-word phrases.
 * 5. Word-by-word token fallback for residual sentences, preserving casing.
 */
export function translateTextToEnglish(text: string): string {
  if (!text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Direct exact match
  if (SPANISH_TO_ENGLISH_MAP[trimmed]) {
    return text.replace(trimmed, SPANISH_TO_ENGLISH_MAP[trimmed]);
  }

  // 2. Case-insensitive exact lookup
  const lower = trimmed.toLowerCase();
  for (const [esKey, enVal] of Object.entries(SPANISH_TO_ENGLISH_MAP)) {
    if (esKey.toLowerCase() === lower) {
      // Preserve uppercase if original is all caps
      if (trimmed === trimmed.toUpperCase() && trimmed.length > 3) {
        return text.replace(trimmed, enVal.toUpperCase());
      }
      return text.replace(trimmed, enVal);
    }
  }

  // 3. Dynamic regex patterns for common UI templates
  let working = text;

  // "Resultados encontrados (X)" -> "Results found (X)"
  working = working.replace(/Resultados encontrados \((.*?)\)/gi, 'Results found ($1)');
  
  // "Pregunta X de Y" -> "Question X of Y"
  working = working.replace(/Pregunta (\d+) de (\d+)/gi, 'Question $1 of $2');

  // "Hace X minutos" -> "X minutes ago"
  working = working.replace(/Hace (\d+) minutos/gi, '$1 minutes ago');
  working = working.replace(/Hace (\d+) horas/gi, '$1 hours ago');
  working = working.replace(/Hace un momento/gi, 'Just now');

  // "X horas certificadas" -> "X certified hours"
  working = working.replace(/(\d+) horas certificadas/gi, '$1 certified hours');
  working = working.replace(/(\d+) evaluaciones/gi, '$1 evaluations');
  working = working.replace(/(\d+) preguntas/gi, '$1 questions');

  // "Límite: X km/h" -> "Limit: X km/h"
  working = working.replace(/Límite:? (\d+) km\/h/gi, 'Limit: $1 km/h');
  working = working.replace(/Velocidad máxima:? (\d+) km\/h/gi, 'Maximum speed: $1 km/h');

  // "Puntaje: X%" -> "Score: X%"
  working = working.replace(/Puntaje:? (\d+)%/gi, 'Score: $1%');
  working = working.replace(/Módulo (\d+):?/gi, 'Module $1:');
  working = working.replace(/Paso (\d+):?/gi, 'Step $1:');

  // 4. Substring / multi-word phrase replacement (ordered by longest multi-word phrases first)
  const phrases = Object.keys(SPANISH_TO_ENGLISH_MAP)
    .filter(k => k.includes(' ') && k.length >= 4)
    .sort((a, b) => b.length - a.length);

  for (const esPhrase of phrases) {
    if (working.includes(esPhrase)) {
      working = working.split(esPhrase).join(SPANISH_TO_ENGLISH_MAP[esPhrase]);
    }
  }

  // 5. Word-by-word token fallback for individual words in residual text
  const tokens = working.split(/(\s+|[.,;:?!()\[\]{}"'¿¡]+)/);
  let changed = false;
  const translatedTokens = tokens.map((token) => {
    if (!token || /^\s+$/.test(token) || /^[.,;:?!()\[\]{}"'¿¡]+$/.test(token)) {
      return token;
    }
    const tokenLower = token.toLowerCase();
    if (SPANISH_TO_ENGLISH_MAP[tokenLower]) {
      changed = true;
      const mapped = SPANISH_TO_ENGLISH_MAP[tokenLower];
      if (token === token.toUpperCase() && token.length > 1) {
        return mapped.toUpperCase();
      }
      if (token[0] === token[0].toUpperCase()) {
        return mapped.charAt(0).toUpperCase() + mapped.slice(1);
      }
      return mapped;
    }
    return token;
  });

  if (changed) {
    working = translatedTokens.join('');
  }

  return working;
}

